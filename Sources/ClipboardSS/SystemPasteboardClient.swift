import AppKit
import ClipboardCore

final class SystemPasteboardClient: PasteboardClient {
    private let pasteboard: NSPasteboard

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    func currentChangeCount() -> Int {
        pasteboard.changeCount
    }

    /// nspasteboard.org markers (plus 1Password's legacy type) that the source
    /// app sets on passwords and other items clipboard managers must not keep.
    static let sensitiveTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    func readSnapshot() -> ClipboardSnapshot {
        let types = pasteboard.types ?? []
        if types.contains(where: Self.sensitiveTypes.contains) {
            // Do not read the payload at all.
            return ClipboardSnapshot(text: nil, imageData: nil, isSensitive: true)
        }

        let imageData = pasteboard.data(forType: .png)
            ?? pasteboard.data(forType: .tiff)
            ?? imageDataFromReadableObject()
        let text = pasteboard.string(forType: .string)
        return ClipboardSnapshot(text: text, imageData: imageData)
    }

    func clearContents() {
        pasteboard.clearContents()
    }

    func writeText(_ text: String) {
        pasteboard.setString(text, forType: .string)
    }

    /// Writes the original bytes so the next read hashes the same as the stored
    /// clip: PNG under `.png`, TIFF under `.tiff`. Other formats (JPEG, HEIC)
    /// are converted to PNG, since `.png` must hold PNG data.
    func writeImageData(_ data: Data) {
        if Self.isTIFF(data) {
            pasteboard.setData(data, forType: .tiff)
        } else if Self.isPNG(data) {
            pasteboard.setData(data, forType: .png)
        } else {
            pasteboard.setData(NSImage(data: data)?.pngData() ?? data, forType: .png)
        }
    }

    static func isPNG(_ data: Data) -> Bool {
        data.starts(with: [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
    }

    static func isTIFF(_ data: Data) -> Bool {
        data.starts(with: [0x49, 0x49, 0x2A, 0x00]) || data.starts(with: [0x4D, 0x4D, 0x00, 0x2A])
    }

    private func imageDataFromReadableObject() -> Data? {
        let images = pasteboard.readObjects(forClasses: [NSImage.self]) as? [NSImage]
        return images?.first?.pngData()
    }
}

